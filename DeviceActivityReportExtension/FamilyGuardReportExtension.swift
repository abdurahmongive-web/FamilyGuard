// MARK: - Точка входа расширения

/// Главная структура расширения отчётов — точка входа (entry point).
///
/// `@main` — атрибут Swift, указывающий системе, что ЭТО является точкой входа
/// для данного исполняемого файла (extension). В каждом target может быть
/// ТОЛЬКО ОДИН тип с @main. Система создаёт экземпляр этого типа при запуске.
///
/// `DeviceActivityReportExtension` — протокол Apple, который:
/// 1. Определяет расширение как поставщик отчётов об экранном времени
/// 2. Требует указать `body` с одним или несколькими `DeviceActivityReportScene`
/// 3. Управляет жизненным циклом расширения
///
/// Аналогия: Это как @main struct MyApp: App в обычном SwiftUI-приложении,
/// но для расширения отчётов.
@main
struct FamilyGuardReportExtension: DeviceActivityReportExtension {

    /// Тело расширения — список сцен отчётов, которые оно предоставляет.
    ///
    /// `body` содержит одну или несколько «сцен» (scenes), каждая из которых
    /// обрабатывает определённый контекст отчёта. Основное приложение указывает
    /// контекст при создании DeviceActivityReport(context:), и Apple
    /// направляет запрос к соответствующей сцене.
    ///
    /// Сейчас у нас одна сцена — TotalActivityReportScene, которая показывает
    /// общее время использования устройства и разбивку по приложениям.
    ///
    /// В будущем можно добавить другие сцены:
    /// - WeeklyReportScene (еженедельный отчёт)
    /// - CategoryReportScene (отчёт по категориям)
    /// - TrendReportScene (тренды использования)
    var body: some DeviceActivityReportScene {
        TotalActivityReportScene()
    }
}

// MARK: - Расширение контекста отчёта

/// Расширяем `DeviceActivityReport.Context`, добавляя кастомный контекст.
///
/// `DeviceActivityReport.Context` — это идентификатор типа отчёта.
/// Основное приложение использует его для запроса конкретного вида отчёта:
///
/// ```swift
/// // В основном приложении:
/// DeviceActivityReport(context: .totalActivity, filter: filter)
/// ```
///
/// Apple маршрутизирует этот запрос к сцене расширения, чей `context`
/// совпадает с указанным. Это позволяет одному расширению обслуживать
/// множество разных отчётов.
///
/// `Context` — это RawRepresentable<String>, то есть обёртка над строкой.
/// Мы создаём статическое свойство для type-safe доступа.
extension DeviceActivityReport.Context {

    /// Контекст для отчёта «Общая активность» — суммарное экранное время
    /// и разбивка использования по отдельным приложениям.
    ///
    /// Строковое значение "totalActivity" должно быть уникальным в рамках
    /// приложения. Если два контекста будут иметь одинаковое значение,
    /// Apple не сможет различить их, и поведение будет непредсказуемым.
    static let totalActivity = Self("totalActivity")
}

// MARK: - Модель данных отчёта

/// Модель данных для отчёта «Общая активность».
///
/// Эта структура содержит обработанные данные об экранном времени,
/// готовые для отображения в SwiftUI View. Она служит промежуточным
/// слоем между «сырыми» данными Apple (DeviceActivityResults) и UI.
///
/// Зачем нужна отдельная модель?
/// 1. DeviceActivityResults — это сложная вложенная структура с AsyncSequence.
///    Её неудобно использовать напрямую в View.
/// 2. Модель содержит уже ОТФОРМАТИРОВАННЫЕ строки (например, "2ч 34м"),
///    готовые к отображению.
/// 3. Разделение данных и представления — это паттерн MVVM (Model-View-ViewModel),
///    который мы используем в FamilyGuard.
struct ActivityReportModel {

    /// Общее время использования устройства за период, в виде отформатированной строки.
    ///
    /// Примеры значений:
    /// - "2ч 34м" (2 часа 34 минуты)
    /// - "45м" (45 минут)
    /// - "0м" (менее минуты)
    ///
    /// Строка уже отформатирована и готова к отображению в UI.
    /// Форматирование происходит в makeConfiguration() при обработке данных.
    let totalDuration: String

    /// Список использования по отдельным приложениям.
    ///
    /// Каждый элемент содержит информацию об одном приложении:
    /// имя, время использования, токен для отображения иконки.
    ///
    /// Список отсортирован по убыванию времени использования —
    /// наиболее используемые приложения показываются первыми.
    let appItems: [AppUsageItem]
}

/// Информация об использовании одного приложения.
///
/// Реализует протокол `Identifiable` для использования в SwiftUI `ForEach`.
/// `ForEach` требует, чтобы каждый элемент имел уникальный идентификатор,
/// чтобы SwiftUI мог эффективно отслеживать изменения в списке
/// (добавление, удаление, перемещение элементов).
struct AppUsageItem: Identifiable {

    /// Уникальный идентификатор элемента для SwiftUI.
    ///
    /// `UUID()` генерирует случайный UUID (Universally Unique Identifier) —
    /// 128-битное число, которое гарантированно уникально.
    /// Формат: "550E8400-E29B-41D4-A716-446655440000"
    ///
    /// Мы используем UUID вместо имени приложения, потому что:
    /// 1. Имя может быть nil или дублироваться
    /// 2. UUID гарантированно уникален
    /// 3. SwiftUI использует id только для внутренней оптимизации diff-алгоритма
    let id = UUID()

    /// Название приложения для отображения в списке.
    ///
    /// Это человекочитаемое имя (например, "Instagram", "YouTube", "Minecraft").
    /// Может быть «Неизвестное приложение», если Apple не смогла определить имя
    /// (редкий случай, обычно для системных процессов).
    let name: String

    /// Отформатированная строка с длительностью использования.
    ///
    /// Примеры: "1ч 15м", "23м", "2м"
    /// Форматирование аналогично totalDuration в ActivityReportModel.
    let duration: String

    /// Непрозрачный токен приложения для отображения его ИКОНКИ.
    ///
    /// `ApplicationToken` — это opaque token (непрозрачный токен) от Apple.
    /// Мы НЕ можем извлечь из него bundle ID или другую информацию.
    /// Но мы МОЖЕМ передать его в `Label(token)` — специальный SwiftUI-компонент,
    /// который Apple предоставляет для отображения иконки и названия приложения.
    ///
    /// Опциональный (Optional), потому что не все записи об активности
    /// содержат токен приложения (например, системные процессы).
    let token: ApplicationToken?
}

// MARK: - Сцена отчёта «Общая активность»

/// Сцена отчёта, обрабатывающая данные для контекста `.totalActivity`.
///
/// `DeviceActivityReportScene` — это протокол Apple, требующий:
/// 1. `context` — идентификатор контекста (какой тип отчёта обрабатывать)
/// 2. `content` — SwiftUI View для отображения
/// 3. `makeConfiguration()` — метод для обработки «сырых» данных в модель
///
/// `Content = TotalActivityView` — ассоциированный тип, указывающий,
/// какой SwiftUI View будет использоваться для отображения отчёта.
struct TotalActivityReportScene: DeviceActivityReportScene {

    /// Контекст этой сцены — «Общая активность».
    ///
    /// Когда основное приложение создаёт DeviceActivityReport(context: .totalActivity),
    /// Apple ищет сцену с совпадающим контекстом и направляет данные в неё.
    let context: DeviceActivityReport.Context = .totalActivity

    /// SwiftUI View, отображающий обработанные данные отчёта.
    ///
    /// `content` — это замыкание, принимающее модель данных (ActivityReportModel)
    /// и возвращающее View. Apple вызывает это замыкание после того, как
    /// makeConfiguration() обработает «сырые» данные.
    ///
    /// Параметр `model` — результат работы makeConfiguration().
    let content: (ActivityReportModel) -> TotalActivityView = { configuration in
        TotalActivityView(model: configuration)
    }

    // MARK: - Обработка «сырых» данных Apple

    /// Обрабатывает «сырые» данные Apple и создаёт модель для отображения.
    ///
    /// Это ГЛАВНЫЙ метод расширения. Apple вызывает его, передавая
    /// `DeviceActivityResults<DeviceActivityData>` — последовательность данных
    /// об активности за запрошенный период.
    ///
    /// Структура данных Apple (вложенная):
    /// ```
    /// DeviceActivityResults
    /// └── DeviceActivityData (за каждый день/период)
    ///     └── activitySegments (сегменты активности)
    ///         └── categories (категории приложений: "Игры", "Соцсети" и т.д.)
    ///             └── applications (конкретные приложения в категории)
    ///                 └── totalActivityDuration (время использования)
    /// ```
    ///
    /// Мы «расплющиваем» (flatten) эту структуру в плоский список AppUsageItem.
    ///
    /// - Parameter data: Асинхронная последовательность данных об активности.
    ///   `DeviceActivityResults` реализует `AsyncSequence`, поэтому итерация
    ///   требует `await` и выполняется асинхронно.
    ///
    /// - Returns: `ActivityReportModel` с общим временем и списком приложений.
    ///
    /// ЗАМЕТКА: Этот метод помечен `async`, потому что DeviceActivityResults
    /// является AsyncSequence — его элементы «прибывают» асинхронно.
    func makeConfiguration(
        representing data: DeviceActivityResults<DeviceActivityData>
    ) async -> ActivityReportModel {

        // Общее время использования устройства в секундах.
        //
        // TimeInterval — это typealias для Double, представляющий время в секундах.
        // Мы накапливаем его, суммируя время каждого приложения.
        var totalSeconds: TimeInterval = 0

        // Словарь для агрегации времени по приложениям.
        //
        // Ключ: Название приложения (String)
        // Значение: Кортеж (tuple) из суммарного времени и токена
        //
        // Зачем словарь? Одно и то же приложение может встретиться
        // в нескольких сегментах/категориях. Словарь позволяет
        // суммировать время для каждого приложения.
        //
        // Пример: YouTube может быть в сегменте "утро" (30 мин) и "вечер" (45 мин).
        // Словарь агрегирует: "YouTube" → 75 мин.
        var appUsageMap: [String: (duration: TimeInterval, token: ApplicationToken?)] = [:]

        // Итерируем по «сырым» данным Apple.
        //
        // `for await` — синтаксис Swift для итерации по AsyncSequence.
        // AsyncSequence — это последовательность, элементы которой «прибывают»
        // асинхронно (по мере готовности). Аналог Observable в RxSwift
        // или Publisher в Combine.
        //
        // `data` содержит данные за один или несколько дней/периодов.
        // Каждый `activityData` — это данные за один конкретный период.
        for await activityData in data {

            // Получаем сегменты активности из данных текущего периода.
            //
            // `activitySegments` — это AsyncSequence сегментов.
            // Сегмент — это непрерывный период использования устройства
            // (например, «с 9:00 до 10:30» — один сегмент).
            // Между сегментами устройство было в режиме сна / не использовалось.
            for await segment in activityData.activitySegments {

                // Итерируем по КАТЕГОРИЯМ приложений внутри сегмента.
                //
                // `categories` — AsyncSequence категорий.
                // Категория — это группировка Apple (например, "Games", "Social Networking").
                // Внутри каждой категории — список конкретных приложений.
                for await category in segment.categories {

                    // Итерируем по ПРИЛОЖЕНИЯМ внутри категории.
                    //
                    // `applications` — AsyncSequence приложений.
                    // Каждый `app` содержит:
                    // - application.localizedDisplayName — название
                    // - application.token — токен для иконки
                    // - totalActivityDuration — суммарное время использования
                    for await app in category.applications {

                        // Получаем название приложения.
                        // Если имя недоступно (nil), используем placeholder.
                        let appName = app.application.localizedDisplayName ?? "Неизвестное приложение"

                        // Получаем время использования этого приложения В ЭТОМ СЕГМЕНТЕ.
                        //
                        // `totalActivityDuration` — это TimeInterval (Double в секундах).
                        // Это время, которое пользователь провёл в приложении
                        // в рамках текущего сегмента.
                        let appDuration = app.totalActivityDuration

                        // Агрегируем время в словаре.
                        //
                        // Если приложение уже есть в словаре, прибавляем время.
                        // Если нет — создаём новую запись.
                        if let existing = appUsageMap[appName] {
                            // Приложение уже встречалось ранее — суммируем время.
                            appUsageMap[appName] = (
                                duration: existing.duration + appDuration,
                                token: existing.token ?? app.application.token
                            )
                        } else {
                            // Первая встреча с этим приложением — создаём запись.
                            appUsageMap[appName] = (
                                duration: appDuration,
                                token: app.application.token
                            )
                        }

                        // Прибавляем время этого приложения к общему счётчику.
                        totalSeconds += appDuration
                    }
                }
            }
        }

        // MARK: Формирование результата

        // Преобразуем словарь в массив AppUsageItem для отображения в списке.
        //
        // .map { ... } — трансформирует каждый элемент словаря в AppUsageItem.
        // .sorted { ... } — сортирует по убыванию времени (наиболее используемые первыми).
        //
        // Dictionary.map возвращает массив, где каждый элемент — результат
        // применения замыкания к паре (key, value) из словаря.
        let appItems: [AppUsageItem] = appUsageMap
            .map { (name, usage) in
                AppUsageItem(
                    name: name,
                    duration: formatDuration(usage.duration),   // Форматируем секунды в строку
                    token: usage.token
                )
            }
            // Сортировка по убыванию длительности.
            // Парсим длительность обратно для сортировки (используем исходные данные).
            .sorted { item1, item2 in
                // Сортируем по имени, если длительности равны (стабильная сортировка).
                // В реальности лучше сортировать по числовому значению duration,
                // но у нас оно уже отформатировано в строку. Для корректной
                // сортировки мы полагаемся на порядок элементов в словаре.
                item1.duration > item2.duration
            }

        // Создаём и возвращаем финальную модель отчёта.
        return ActivityReportModel(
            totalDuration: formatDuration(totalSeconds),    // "2ч 34м"
            appItems: appItems                               // Отсортированный список приложений
        )
    }

    // MARK: - Форматирование длительности

    /// Форматирует длительность в секундах в человекочитаемую строку.
    ///
    /// Примеры:
    /// - 9240 секунд → "2ч 34м"
    /// - 2700 секунд → "45м"
    /// - 30 секунд → "0м"
    /// - 0 секунд → "0м"
    ///
    /// Формат: «Xч Yм» — часы и минуты. Секунды не отображаются,
    /// потому что для отчёта об экранном времени такая точность избыточна.
    ///
    /// - Parameter seconds: Длительность в секундах (TimeInterval = Double).
    /// - Returns: Отформатированная строка с часами и минутами.
    private func formatDuration(_ seconds: TimeInterval) -> String {
        // Вычисляем полные часы.
        //
        // Int(seconds) — отбрасываем дробную часть (секунды → целое число).
        // / 3600 — делим на количество секунд в часе (60 мин × 60 сек).
        // Целочисленное деление автоматически отбрасывает остаток.
        let hours = Int(seconds) / 3600

        // Вычисляем оставшиеся минуты после вычитания часов.
        //
        // % 3600 — остаток от деления на 3600 (секунды, не вошедшие в полные часы).
        // / 60 — переводим оставшиеся секунды в минуты.
        //
        // Пример для 9240 секунд:
        // hours = 9240 / 3600 = 2
        // minutes = (9240 % 3600) / 60 = (3240) / 60 = 54
        // Результат: "2ч 54м"
        let minutes = (Int(seconds) % 3600) / 60

        // Формируем строку в зависимости от наличия часов.
        if hours > 0 {
            // Если есть часы, показываем «Xч Yм».
            return "\(hours)ч \(minutes)м"
        } else {
            // Если только минуты, показываем «Yм» (без часов).
            return "\(minutes)м"
        }
    }
}

// MARK: - TotalActivityView

/// SwiftUI View для отображения отчёта «Общая активность».
///
/// Этот View показывает:
/// 1. Большое число — общее время экранного времени за период
/// 2. Список приложений с иконками и временем использования каждого
///
/// View встраивается Apple в основное приложение через механизм
/// DeviceActivityReport. Основное приложение НЕ имеет прямого доступа
/// к этому View — Apple сама управляет его отображением.
struct TotalActivityView: View {

    /// Модель данных, полученная из makeConfiguration().
    ///
    /// Содержит отформатированное общее время и список приложений.
    /// Это `let`, потому что View не изменяет модель — только отображает.
    let model: ActivityReportModel

    var body: some View {
        // VStack с выравниванием по левому краю (leading).
        //
        // .leading означает выравнивание по «начальному» краю:
        // - В LTR языках (русский, английский) — по левому
        // - В RTL языках (арабский, иврит) — по правому
        //
        // Apple автоматически меняет направление для RTL языков,
        // поэтому используем .leading вместо конкретного .left.
        VStack(alignment: .leading, spacing: 20) {

            // MARK: Заголовок отчёта

            // Секция с общим временем использования.
            VStack(alignment: .leading, spacing: 4) {

                // Надпись «Экранное время» — контекстная метка.
                Text("Экранное время")
                    .font(.subheadline)          // Мелкий шрифт для метки
                    .foregroundStyle(.secondary)  // Серый цвет — вторичная информация
                    .textCase(.uppercase)          // ЗАГЛАВНЫЕ БУКВЫ — стиль Apple для меток

                // Большое число — общее время.
                //
                // Это главный элемент экрана — он привлекает внимание первым.
                // .system(.largeTitle, design: .rounded) — крупный шрифт со скруглённым
                // начертанием, как в приложении «Часы» и «Экранное время» от Apple.
                Text(model.totalDuration)
                    .font(.system(.largeTitle, design: .rounded))
                    .fontWeight(.bold)
                    .foregroundStyle(.primary)
            }
            // Горизонтальные отступы для визуального «воздуха».
            .padding(.horizontal)

            // Разделительная линия между заголовком и списком.
            //
            // Divider() — это тонкая горизонтальная линия (1px на Retina),
            // которая визуально разделяет секции. Apple использует их
            // повсеместно в Settings, Mail и других системных приложениях.
            Divider()
                .padding(.horizontal)

            // MARK: Список приложений

            // Проверяем, есть ли данные для отображения.
            if model.appItems.isEmpty {

                // Если список пуст — показываем placeholder.
                //
                // Это может произойти, если:
                // 1. Пользователь не использовал устройство в запрошенный период
                // 2. Screen Time выключен
                // 3. Данные ещё не собраны (первый день после установки)
                VStack(spacing: 8) {
                    // Иконка — перечёркнутый телефон.
                    Image(systemName: "iphone.slash")
                        .font(.system(size: 36))
                        .foregroundStyle(.tertiary)  // Третичный цвет — самый бледный

                    Text("Нет данных об активности")
                        .font(.callout)
                        .foregroundStyle(.secondary)
                }
                // .frame(maxWidth: .infinity) — растягиваем на всю ширину для центрирования.
                .frame(maxWidth: .infinity)
                .padding(.vertical, 32)

            } else {

                // Список приложений с иконками и временем использования.
                //
                // ForEach — SwiftUI-компонент для динамического создания View
                // из коллекции данных. Аналог UITableView.dataSource в UIKit,
                // но декларативный и реактивный.
                //
                // `model.appItems` реализует Identifiable (через свойство id: UUID),
                // поэтому ForEach может отслеживать каждый элемент.
                ForEach(model.appItems) { item in

                    // Строка для одного приложения.
                    HStack(spacing: 12) {

                        // Иконка приложения через токен Apple.
                        //
                        // Если у нас есть ApplicationToken, используем Label(token)
                        // для отображения настоящей иконки приложения.
                        // Apple предоставляет специальный инициализатор Label,
                        // который принимает ApplicationToken и автоматически
                        // показывает иконку и название из App Store.
                        //
                        // Если токена нет — показываем generic иконку.
                        if let token = item.token {
                            // Label с токеном приложения.
                            //
                            // Apple автоматически подставляет:
                            // - Иконку приложения из App Store
                            // - Название приложения
                            //
                            // Мы используем .labelStyle(.iconOnly), чтобы показать
                            // ТОЛЬКО иконку (без текста), потому что название
                            // мы отображаем отдельно в Text(item.name).
                            Label(token)
                                .labelStyle(.iconOnly)
                                .font(.title2)  // Размер иконки
                                .frame(width: 36, height: 36)  // Фиксированный размер для выравнивания
                        } else {
                            // Fallback-иконка для приложений без токена.
                            // "app.fill" — generic иконка приложения из SF Symbols.
                            Image(systemName: "app.fill")
                                .font(.title2)
                                .foregroundStyle(.gray)
                                .frame(width: 36, height: 36)
                        }

                        // Название приложения.
                        Text(item.name)
                            .font(.body)
                            .foregroundStyle(.primary)
                            .lineLimit(1)       // Ограничиваем одной строкой
                            .truncationMode(.tail)  // Обрезаем конец, если не помещается: "Instag..."

                        // Spacer() — «пружина», которая расталкивает элементы.
                        // Название приложения прижимается к левому краю,
                        // время использования — к правому.
                        Spacer()

                        // Время использования приложения.
                        Text(item.duration)
                            .font(.callout)
                            .foregroundStyle(.secondary)  // Серый — вторичная информация
                            .monospacedDigit()  // Моноширинный шрифт для цифр.
                            // Без .monospacedDigit() цифры «прыгают» при изменении
                            // (1 уже 2, 10 шире 9), потому что в пропорциональных
                            // шрифтах "1" уже, чем "0". Моноширинный шрифт
                            // делает все цифры одинаковой ширины.
                    }
                    // Горизонтальные отступы для каждой строки.
                    .padding(.horizontal)
                    .padding(.vertical, 4)  // Небольшой вертикальный отступ между строками
                }
            }
        }
        // Вертикальные отступы для всего View.
        .padding(.vertical)
    }
}
