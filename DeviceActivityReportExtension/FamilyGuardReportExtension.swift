// ║                                                                    ║
// ║  Apple НЕ позволяет основному приложению напрямую читать данные    ║
// ║  об экранном времени. Вместо этого, расширение DeviceActivityReport ║
// ║  получает данные от Apple, обрабатывает их, и возвращает готовый    ║
// ║  SwiftUI View, который основное приложение встраивает через        ║
// ║  DeviceActivityReport(context:filter:) — специальный контейнер.    ║
// ║                                                                    ║
