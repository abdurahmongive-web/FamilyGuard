// ErrorView.swift
// FamilyGuard
//
// Переиспользуемый компонент для отображения ошибок в любом месте приложения.
//
// ╔══════════════════════════════════════════════════════════════════════╗
// ║  ErrorView — это универсальный View-компонент, который показывает   ║
// ║  пользователю информацию об ошибке в стандартизированном виде:      ║
// ║                                                                    ║
// ║       ❗️ (красная иконка)                                          ║
// ║       Заголовок ошибки                                             ║
// ║       Описание ошибки                                              ║
// ║       [Попробовать снова] (опционально)                            ║
// ║                                                                    ║
// ║  Используется по всему приложению: на экранах загрузки данных,     ║
// ║  при сетевых ошибках, при отказе в разрешениях и т.д.             ║
// ╚══════════════════════════════════════════════════════════════════════╝
//
// Принципы дизайна:
// 1. ЕДИНООБРАЗИЕ — все ошибки выглядят одинаково, пользователь сразу
//    узнаёт паттерн и знает, что делать.
// 2. ИНФОРМАТИВНОСТЬ — заголовок + описание дают достаточно информации
//    для понимания проблемы.
// 3. ДЕЙСТВИЕ — опциональная кнопка «Попробовать снова» даёт пользователю
//    возможность решить проблему самостоятельно.
// 4. АДАПТИВНОСТЬ — поддержка Light/Dark mode, Dynamic Type, VoiceOver.

import SwiftUI  // Фреймворк декларативного UI от Apple.
                // Весь интерфейс FamilyGuard построен на SwiftUI.
                // SwiftUI использует декларативный подход: мы ОПИСЫВАЕМ,
                // как должен выглядеть интерфейс, а Apple сама отрисовывает его.

// MARK: - ErrorView

/// Переиспользуемый View-компонент для стандартизированного отображения ошибок.
///
/// ## Использование
///
/// Простейший вариант (без кнопки повтора):
/// ```swift
/// ErrorView(
///     title: "Не удалось загрузить данные",
///     message: "Проверьте подключение к интернету."
/// )
/// ```
///
/// С кнопкой повтора:
/// ```swift
/// ErrorView(
///     title: "Ошибка сети",
///     message: "Сервер не отвечает.",
///     retryAction: {
///         await viewModel.loadData()
///     }
/// )
/// ```
///
/// Полноэкранный режим (с Spacer внутри ZStack/VStack):
/// ```swift
/// VStack {
///     Spacer()
///     ErrorView(title: "404", message: "Страница не найдена")
///     Spacer()
/// }
/// ```
struct ErrorView: View {

    // MARK: - Свойства (Properties)

    /// Заголовок ошибки — краткое описание проблемы.
    ///
    /// Примеры хороших заголовков:
    /// - "Не удалось загрузить данные"
    /// - "Нет подключения к интернету"
    /// - "Доступ запрещён"
    /// - "Время ожидания истекло"
    ///
    /// Это `let` (константа), потому что ErrorView обычно создаётся заново
    /// при каждом изменении состояния, а не мутируется.
    let title: String

    /// Подробное описание ошибки — объясняет причину и/или предлагает решение.
    ///
    /// Примеры хороших сообщений:
    /// - "Проверьте подключение к интернету и попробуйте снова."
    /// - "У приложения нет разрешения на доступ к Screen Time. Откройте Настройки."
    /// - "Сервер временно недоступен. Попробуйте позже."
    ///
    /// Хорошее сообщение отвечает на вопросы: «Что пошло не так?» и «Что мне делать?»
    let message: String

    /// Опциональное замыкание (closure), выполняемое при нажатии кнопки «Попробовать снова».
    ///
    /// Если `retryAction` равен `nil`, кнопка НЕ отображается — View содержит
    /// только иконку, заголовок и сообщение.
    ///
    /// Тип `(() -> Void)?`:
    /// - `()` — функция не принимает аргументов
    /// - `-> Void` — функция ничего не возвращает
    /// - `?` — функция опциональна (может быть nil)
    ///
    /// Пример: `retryAction: { viewModel.reload() }`
    ///
    /// Мы используем синхронное замыкание (не async), чтобы вызывающий код
    /// сам решал, как обрабатывать асинхронность (через Task { }, например).
    let retryAction: (() -> Void)?

    // MARK: - Инициализатор

    /// Создаёт новый ErrorView с заданными параметрами.
    ///
    /// - Parameter title: Краткий заголовок ошибки (обязательный).
    /// - Parameter message: Подробное описание ошибки (обязательный).
    /// - Parameter retryAction: Замыкание для кнопки «Попробовать снова» (опциональный).
    ///   Если nil — кнопка не показывается.
    ///
    /// Значение по умолчанию для retryAction — `nil`, что позволяет создавать
    /// ErrorView без указания этого параметра:
    /// ```swift
    /// ErrorView(title: "Ошибка", message: "Что-то пошло не так")
    /// // retryAction автоматически = nil, кнопка не показывается
    /// ```
    init(
        title: String,
        message: String,
        retryAction: (() -> Void)? = nil   // Значение по умолчанию — nil (кнопка скрыта)
    ) {
        self.title = title
        self.message = message
        self.retryAction = retryAction
    }

    // MARK: - Тело View (Body)

    /// Основное содержимое View — описывает, как выглядит компонент.
    ///
    /// В SwiftUI `body` — это computed property (вычисляемое свойство),
    /// которое возвращает описание интерфейса. SwiftUI вызывает его каждый раз,
    /// когда нужно перерисовать View (при изменении @State, @Binding и т.д.).
    ///
    /// `some View` — это opaque return type (непрозрачный тип возврата).
    /// Он говорит компилятору: «Я верну какой-то конкретный тип, реализующий
    /// протокол View, но какой именно — определю сам». Это позволяет
    /// компилятору оптимизировать код, зная точный тип во время компиляции.
    var body: some View {

        // VStack — вертикальный стек, располагающий дочерние элементы сверху вниз.
        //
        // `spacing: 16` — расстояние между элементами в поинтах (points).
        // 1 point = 1 пиксель на обычном экране, 2 пикселя на Retina, 3 на Super Retina.
        // 16pt — стандартный отступ в iOS Design Guidelines для визуального разделения
        // логических блоков (не слишком тесно, не слишком просторно).
        VStack(spacing: 16) {

            // MARK: Иконка ошибки

            // Иконка — красный восклицательный знак в треугольнике.
            //
            // "exclamationmark.triangle.fill" — это имя иконки из SF Symbols,
            // библиотеки 5000+ векторных иконок Apple. Эта конкретная иконка —
            // заполненный треугольник с восклицательным знаком, универсальный
            // символ предупреждения/ошибки, понятный во всех культурах.
            //
            // Альтернативы:
            // - "xmark.circle.fill" — крестик в круге (для фатальных ошибок)
            // - "exclamationmark.circle.fill" — восклицательный знак в круге
            // - "wifi.slash" — для ошибок сети
            Image(systemName: "exclamationmark.triangle.fill")

                // .font(.system(size: 48)) — задаёт размер иконки.
                //
                // SF Symbols масштабируются как шрифты, поэтому для изменения
                // размера используем .font(), а не .frame().
                // 48pt — достаточно крупный размер, чтобы иконка была
                // заметна, но не доминировала на экране.
                .font(.system(size: 48))

                // .foregroundStyle(.red) — красный цвет иконки.
                //
                // .foregroundStyle() — современный API (iOS 15+) для установки цвета.
                // Предшественник .foregroundColor() устарел (deprecated).
                //
                // .red — системный красный, который Apple адаптирует:
                // - В Light mode: яркий красный (#FF3B30)
                // - В Dark mode: чуть более мягкий красный (#FF453A)
                // Это обеспечивает оптимальный контраст в обоих режимах.
                .foregroundStyle(.red)

                // .symbolRenderingMode(.hierarchical) — иерархический режим отрисовки.
                //
                // SF Symbols поддерживают несколько режимов отрисовки:
                // - .monochrome — одноцветный (по умолчанию)
                // - .hierarchical — иерархический: основной цвет + полупрозрачные слои
                // - .palette — многоцветный с пользовательскими цветами
                // - .multicolor — многоцветный, определённый Apple
                //
                // .hierarchical делает треугольник чуть темнее/светлее восклицательного
                // знака, создавая глубину и визуальный интерес. Это выглядит
                // профессиональнее, чем плоский одноцветный вариант.
                .symbolRenderingMode(.hierarchical)

                // Добавляем метку доступности для VoiceOver.
                //
                // VoiceOver — это технология для людей с нарушениями зрения.
                // Когда VoiceOver включён, iOS произносит вслух содержимое экрана.
                // Без .accessibilityLabel() VoiceOver прочитал бы техническое имя
                // иконки ("exclamationmark triangle fill"), что неинформативно.
                // С меткой "Ошибка" VoiceOver скажет: «Ошибка, изображение».
                .accessibilityLabel("Ошибка")

            // MARK: Заголовок ошибки

            // Текстовый элемент с заголовком ошибки.
            Text(title)

                // .font(.title2) — предопределённый стиль шрифта Apple.
                //
                // Apple определяет иерархию стилей:
                // .largeTitle (34pt) > .title (28pt) > .title2 (22pt) > .title3 (20pt)
                // > .headline (17pt, bold) > .body (17pt) > .callout (16pt)
                // > .subheadline (15pt) > .footnote (13pt) > .caption (12pt)
                //
                // .title2 — хороший баланс: достаточно крупный для заголовка,
                // но не настолько большой, чтобы занимать весь экран.
                // Эти размеры автоматически увеличиваются при включении Dynamic Type
                // (настройка «Размер текста» в Настройках iOS).
                .font(.title2)

                // .fontWeight(.bold) — жирное начертание.
                // Делает заголовок визуально «тяжелее», привлекая внимание.
                // Альтернативы: .regular, .medium, .semibold, .bold, .heavy, .black
                .fontWeight(.bold)

                // .foregroundStyle(.primary) — основной цвет текста.
                //
                // .primary — это СЕМАНТИЧЕСКИЙ цвет Apple:
                // - В Light mode: почти чёрный
                // - В Dark mode: почти белый
                //
                // Семантические цвета автоматически адаптируются к теме оформления.
                // Это ГОРАЗДО лучше, чем жёстко задавать .black или .white,
                // которые будут нечитаемы в противоположной теме.
                .foregroundStyle(.primary)

                // .multilineTextAlignment(.center) — выравнивание текста по центру.
                // Если заголовок длинный и переносится на несколько строк,
                // каждая строка будет отцентрирована.
                .multilineTextAlignment(.center)

            // MARK: Описание ошибки

            // Текстовый элемент с подробным описанием ошибки.
            Text(message)

                // .font(.body) — основной стиль текста для основного контента.
                // 17pt по умолчанию — оптимальный размер для чтения.
                .font(.body)

                // .foregroundStyle(.secondary) — вторичный цвет текста.
                //
                // .secondary — семантический цвет, менее контрастный чем .primary:
                // - В Light mode: серый (~60% прозрачности)
                // - В Dark mode: светло-серый (~60% прозрачности)
                //
                // Это создаёт визуальную иерархию: заголовок (primary, bold) важнее,
                // описание (secondary, regular) — дополнительная информация.
                .foregroundStyle(.secondary)

                // Центрирование многострочного текста.
                .multilineTextAlignment(.center)

            // MARK: Кнопка «Попробовать снова» (опциональная)

            // Проверяем, задано ли замыкание retryAction.
            //
            // `if let action = retryAction` — это Optional Binding (привязка опционала).
            // Если retryAction НЕ nil, значение «разворачивается» в константу `action`,
            // и блок кода выполняется. Если nil — блок пропускается, кнопка не создаётся.
            //
            // В SwiftUI это УСЛОВНОЕ включение View в иерархию.
            // Когда retryAction = nil, кнопка полностью отсутствует в View-дереве,
            // а не просто скрыта. Это эффективнее, чем .hidden() или .opacity(0).
            if let action = retryAction {

                // Button — интерактивный элемент SwiftUI.
                //
                // Первый параметр — замыкание `action:`, которое выполняется при нажатии.
                // Второй параметр — замыкание `label:`, описывающее внешний вид кнопки.
                //
                // Здесь `action: action` передаёт наше замыкание retryAction
                // как обработчик нажатия кнопки.
                Button(action: action) {

                    // Содержимое кнопки — текст + иконка (в горизонтальном стеке).
                    //
                    // Label — это SwiftUI-компонент, объединяющий текст и иконку.
                    // Он семантически правильнее, чем HStack { Image; Text },
                    // потому что VoiceOver и другие технологии доступности
                    // понимают, что иконка и текст — единое целое.
                    Label {
                        // Текст кнопки.
                        Text("Попробовать снова")
                    } icon: {
                        // Иконка кнопки — стрелка обновления (refresh).
                        // "arrow.clockwise" — круговая стрелка по часовой стрелке,
                        // универсальный символ «повторить» / «обновить».
                        Image(systemName: "arrow.clockwise")
                    }
                    // .font(.headline) — жирный текст стандартного размера (17pt bold).
                    // Делает кнопку заметной, но не чрезмерно крупной.
                    .font(.headline)

                    // .foregroundStyle(.white) — белый цвет текста и иконки.
                    // Контрастирует с индиго фоном кнопки (задан ниже).
                    .foregroundStyle(.white)

                    // .padding(.horizontal, 24) — горизонтальные отступы внутри кнопки.
                    // 24pt слева и справа — текст не «прилипает» к краям кнопки.
                    .padding(.horizontal, 24)

                    // .padding(.vertical, 12) — вертикальные отступы внутри кнопки.
                    // 12pt сверху и снизу — кнопка имеет комфортную высоту для нажатия.
                    //
                    // Apple рекомендует минимальную область нажатия 44×44pt.
                    // С нашими отступами кнопка значительно превышает этот минимум,
                    // обеспечивая комфортное взаимодействие.
                    .padding(.vertical, 12)

                    // .background(.indigo) — индиго фон кнопки.
                    // Индиго (#4B0082) — фирменный цвет FamilyGuard.
                    // Этот цвет адаптируется к Light/Dark mode (системный .indigo).
                    .background(.indigo)

                    // .clipShape(Capsule()) — скругление кнопки в форме «капсулы».
                    //
                    // Capsule() — это форма с полностью скруглёнными краями
                    // (как стадион / ипподром). Это популярный дизайн-паттерн
                    // в iOS, который Apple использует в своих приложениях.
                    //
                    // Альтернативы:
                    // - RoundedRectangle(cornerRadius: 12) — скруглённый прямоугольник
                    // - Circle() — круг (для квадратных кнопок)
                    .clipShape(Capsule())
                }
                // Добавляем верхний отступ перед кнопкой для визуального разделения
                // от текста описания ошибки.
                .padding(.top, 8)
            }
        }
        // Отступы от краёв родительского контейнера.
        //
        // .padding(32) добавляет 32pt со ВСЕХ четырёх сторон.
        // Это предотвращает «прилипание» контента к краям экрана.
        // 32pt — увеличенный отступ (стандартный — 16pt), потому что
        // ErrorView обычно отображается в центре экрана и выглядит лучше
        // с бо́льшим «воздухом» вокруг.
        .padding(32)

        // Ограничиваем максимальную ширину View.
        //
        // На iPad или в landscape-режиме iPhone контент может растянуться
        // на всю ширину экрана, что выглядит некрасиво. .frame(maxWidth: 400)
        // ограничивает ширину до 400pt, обеспечивая оптимальную длину строки
        // для чтения (65-75 символов — типографическая рекомендация).
        //
        // `.infinity` для maxWidth внешнего VStack не нужен, потому что
        // мы хотим, чтобы ErrorView занимал только столько места, сколько нужно.
        .frame(maxWidth: 400)
    }
}

// MARK: - Превью (Preview)

/// Превью для Canvas в Xcode — позволяет видеть ErrorView прямо в редакторе
/// без запуска приложения на симуляторе.
///
/// `#Preview` — это макрос Swift (доступен с iOS 17 / Xcode 15),
/// который заменяет устаревший `PreviewProvider` protocol.
/// Макрос проще, требует меньше boilerplate-кода.
///
/// Можно создать несколько превью для разных состояний:
/// - С кнопкой повтора
/// - Без кнопки повтора
/// - С длинным текстом
/// - В Dark mode
#Preview("С кнопкой повтора") {
    // Пример ErrorView с кнопкой «Попробовать снова».
    ErrorView(
        title: "Не удалось загрузить данные",
        message: "Проверьте подключение к интернету и попробуйте снова.",
        retryAction: {
            // Замыкание-заглушка для превью.
            // В реальном приложении здесь будет вызов viewModel.loadData()
            print("Повторная попытка загрузки...")
        }
    )
}

#Preview("Без кнопки повтора") {
    // Пример ErrorView без кнопки — только информация.
    ErrorView(
        title: "Доступ запрещён",
        message: "У приложения нет разрешения на использование Screen Time. Откройте Настройки → Экранное время."
    )
}

#Preview("Тёмная тема") {
    // Превью в Dark mode для проверки адаптивности цветов.
    ErrorView(
        title: "Ошибка сети",
        message: "Сервер временно недоступен. Пожалуйста, попробуйте позже.",
        retryAction: { }
    )
    // .preferredColorScheme(.dark) — переключает превью в Dark mode.
    // Позволяет убедиться, что семантические цвета (.primary, .secondary)
    // корректно адаптируются.
    .preferredColorScheme(.dark)
}
